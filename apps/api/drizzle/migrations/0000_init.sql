-- BR-06: resolve ghost links when a note with the matching title appears or is renamed.
CREATE OR REPLACE FUNCTION resolve_ghost_links() RETURNS trigger AS $$
BEGIN
  UPDATE note_links
     SET target_note_id = NEW.id
   WHERE user_id = NEW.user_id
     AND target_note_id IS NULL
     AND target_title_norm = NEW.title_norm;
  RETURN NEW;
END $$ LANGUAGE plpgsql;--> statement-breakpoint
CREATE TRIGGER notes_resolve_ghosts AFTER INSERT OR UPDATE OF title ON notes
  FOR EACH ROW WHEN (NEW.deleted_at IS NULL)
  EXECUTE FUNCTION resolve_ghost_links();--> statement-breakpoint

