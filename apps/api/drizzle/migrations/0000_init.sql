-- Application roles (TDD Section H, Database permissions). Roles are created
-- without LOGIN; each environment enables login and sets the password outside
-- migrations (ALTER ROLE nexus_api LOGIN PASSWORD '...'), so no secret is
-- stored in SQL. BYPASSRLS needs elevated rights; where the migration user
-- lacks them, an operator grants it once.
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'nexus_api') THEN
    CREATE ROLE nexus_api NOLOGIN NOBYPASSRLS;
  END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'nexus_maint') THEN
    CREATE ROLE nexus_maint NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'nexus_readonly') THEN
    CREATE ROLE nexus_readonly NOLOGIN;
  END IF;
  BEGIN
    ALTER ROLE nexus_maint BYPASSRLS;
    ALTER ROLE nexus_readonly BYPASSRLS;
  EXCEPTION WHEN insufficient_privilege THEN
    RAISE NOTICE 'BYPASSRLS not granted to maintenance roles: insufficient privilege';
  END;
END $$;--> statement-breakpoint
